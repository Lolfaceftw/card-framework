def test_collect_attempt_metrics_uses_retained_exact_records(tmp_path: Path) -> None:
    """Count revisions, calls, tokens, and every completed synthesis attempt."""
    module = _load_module()
    _write_json(
        tmp_path / "loop_diagnostics.json",
        {
            "converged": True,
            "final_status": "pass",
            "iterations_run": 2,
            "iteration_details": [
                {"critic_status": "fail"},
                {"critic_status": "pass"},
            ],
        },
    )
    for index, agent in enumerate(("Summarizer", "Critic"), start=1):
        _write_json(
            tmp_path / "agent_calls" / f"call_{index}.json",
            {
                "agent": agent,
                "status": "completed",
                "provider_response": {
                    "usage": {
                        "prompt_tokens": 100 * index,
                        "completion_tokens": 10 * index,
                        "total_tokens": 110 * index,
                    }
                },
            },
        )
    _write_json(
        tmp_path / "audio_stage/voice_clone/manifest.json",
        {
            "artifact_count": 2,
            "artifacts": [
                {"output_audio_path": "voice_1.wav"},
                {"output_audio_path": "voice_2.wav"},
            ],
        },
    )
    _write_json(
        tmp_path / "audio_stage/interjector/interjector_manifest.json",
        {
            "artifact_count": 1,
            "rejected_artifact_count": 1,
            "artifacts": [{"repair_attempts": [{}, {}]}],
            "rejected_artifacts": [{"repair_attempts": [{}]}],
        },
    )

    metrics = module._collect_attempt_metrics(tmp_path, condition="estimated")

    assert metrics["loop"]["revision_count"] == 1
    assert metrics["loop"]["critic_pass_count"] == 2
    assert metrics["llm"]["calls_by_agent"] == {"Summarizer": 1, "Critic": 1}
    assert metrics["llm"]["token_usage"]["total_tokens"] == 330
    assert metrics["synthesis"] == {
        "voice_clone_synthesis_count": 2,
        "interjection_synthesis_count": 3,
        "total_synthesis_count": 5,
    }


def test_measured_synthesis_count_includes_live_redrafts(tmp_path: Path) -> None:
    """Use the persistent live count when the final manifest reuses turn audio."""
    module = _load_module()
    voice_root = tmp_path / "audio_stage/voice_clone"
    turn_audio = {
        "turn-1": {"output_audio_path": "voice_1.wav"},
        "turn-2": {"output_audio_path": "voice_2.wav"},
    }
    _write_json(
        voice_root / "manifest.json",
        {
            "artifact_count": 2,
            "artifacts": list(turn_audio.values()),
        },
    )
    _write_json(
        voice_root / "live_draft_example_30s.state.json",
        {"synthesis_count": 7, "turn_audio": turn_audio},
    )
    _write_json(
        tmp_path / "audio_stage/interjector/interjector_manifest.json",
        {
            "artifact_count": 0,
            "rejected_artifact_count": 0,
            "artifacts": [],
            "rejected_artifacts": [],
        },
    )

    metrics = module._collect_synthesis_metrics(tmp_path, condition="measured")

    assert metrics["voice_clone_synthesis_count"] == 7
    assert metrics["total_synthesis_count"] == 7
