"""Regression checks for the strict duration-feedback study runner."""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import sys

from hydra import compose, initialize_config_dir

from card_framework.shared.paths import REPO_ROOT


def _load_module():
    """Load the study script as a module for direct command inspection.

    Returns:
        Imported ``run_duration_feedback_study`` script module.
    """
    script_path = (REPO_ROOT / "scripts/run_duration_feedback_study.py").resolve()
    spec = importlib.util.spec_from_file_location(
        "run_duration_feedback_study",
        script_path,
    )
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _extract_overrides(command: list[str]) -> list[str]:
    """Extract application overrides from the direct Hydra command.

    Args:
        command: Complete Compose command generated by the study runner.

    Returns:
        Ordered Hydra override strings after the Hydra output-directory setting.
    """
    marker_index = command.index("hydra.output_subdir=null")
    return command[marker_index + 1 :]


def _write_json(path: Path, payload: object) -> None:
    """Write one test record with the same JSON shape used by the runner.

    Args:
        path: Destination beneath the temporary attempt directory.
        payload: JSON-serializable record used by a metrics regression check.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload), encoding="utf-8")


def test_condition_commands_share_inputs_and_enforce_strict_context() -> None:
    """Inspect both condition commands against repository-owned input paths.

    The regression gate confirms both conditions share one input and calibration
    while differing in the live-drafting flag that supplies measured feedback.
    It also verifies that no credential value enters the retained argument list.
    """
    module = _load_module()
    output_root = (REPO_ROOT / "artifacts/test-duration-feedback").resolve()
    item = module.PreparedInput(
        episode_index=1,
        episode_title="The Lion, the Lamb & the Meadow (Chap. 12-13)",
        episode_label="01_the_lion_the_lamb_the_meadow_chap_12_13",
        duration_preset="30s",
        target_seconds=30,
        transcript_path=(
            REPO_ROOT / "datasets/sporc/human_eval_assets_10m/package_summary.json"
        ).resolve(),
        calibration_path=(output_root / "calibration.json").resolve(),
    )
    estimated_root = (output_root / "estimated").resolve()
    measured_root = (output_root / "measured").resolve()
    estimated = module._build_run_command(
        item=item,
        condition="estimated",
        attempt_root=estimated_root,
        model=module.DEFAULT_MODEL,
        context_window_tokens=module.DEFAULT_CONTEXT_WINDOW_TOKENS,
        max_iterations=60,
    )
    measured = module._build_run_command(
        item=item,
        condition="measured",
        attempt_root=measured_root,
        model=module.DEFAULT_MODEL,
        context_window_tokens=module.DEFAULT_CONTEXT_WINDOW_TOKENS,
        max_iterations=60,
    )
    estimated_text = " ".join(estimated)
    measured_text = " ".join(measured)

    assert "audio.voice_clone.live_drafting.enabled=false" in estimated_text
    assert "audio.voice_clone.live_drafting.enabled=true" in measured_text
    for command, command_text in (
        (estimated, estimated_text),
        (measured, measured_text),
    ):
        assert "card_framework.cli.main" in command_text
        assert "setup-and-run-gpu --override" not in command_text
        assert "orchestrator.prompt_compaction.enabled=false" in command_text
        assert "orchestrator.prompt_compaction.retry_on_overflow=false" in command_text
        assert "orchestrator.prompt_compaction.max_overflow_retries=0" in command_text
        assert "orchestrator.post_render_duration_verification.enabled=false" in command_text
        assert "+profiles.llm.vllm_local.default_max_tokens=null" in command_text
        assert "audio.interjector.analysis_max_tokens=null" in command_text
        assert "audio.interjector.repair.prompt_max_tokens=null" in command_text
        assert "audio.affect_analysis.reuse_existing_manifest=true" in command_text
        assert "orchestrator.loop_diagnostics.artifact_path=" in command_text
        assert "agents.critic.require_structured_verdict=true" in command_text
        assert "agents.critic.reasoning_loop_guard.enabled=false" in command_text
        assert "session.enabled=false" in command_text
        assert any(
            left == "-e" and right == "CARD_FRAMEWORK_VLLM_API_KEY"
            for left, right in zip(command, command[1:], strict=False)
        )
        assert "HF_HUB_OFFLINE=1" in command
        assert "TRANSFORMERS_OFFLINE=1" in command
    with initialize_config_dir(
        version_base=None,
        config_dir=str((REPO_ROOT / "conf").resolve()),
    ):
        estimated_config = compose(
            config_name="config",
            overrides=_extract_overrides(estimated),
        )
    with initialize_config_dir(
        version_base=None,
        config_dir=str((REPO_ROOT / "conf").resolve()),
    ):
        measured_config = compose(
            config_name="config",
            overrides=_extract_overrides(measured),
        )
    assert estimated_config.audio.voice_clone.live_drafting.enabled is False
    assert measured_config.audio.voice_clone.live_drafting.enabled is True
    assert estimated_config.orchestrator.prompt_compaction.enabled is False
    assert measured_config.orchestrator.prompt_compaction.enabled is False


def test_condition_order_counterbalances_paired_repetitions() -> None:
    """Alternate the first paired condition across repetition numbers.

    The recorded execution sequence limits systematic warm-state bias while the
    study still treats the episode as the independent source observation.
    """
    module = _load_module()

    assert module._condition_order(("estimated", "measured"), 1) == (
        "estimated",
        "measured",
    )
    assert module._condition_order(("estimated", "measured"), 2) == (
        "measured",
        "estimated",
    )


